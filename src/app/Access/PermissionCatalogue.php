        'owner' => ['ar' => 'مالك الجهة', 'en' => 'Owner', 'scopes' => ['tenant']],
        'manager' => ['ar' => 'مدير', 'en' => 'Manager', 'scopes' => ['branches']],
        'supervisor' => ['ar' => 'مشرف قسم', 'en' => 'Department supervisor', 'scopes' => ['department', 'assigned']],
        'sales' => ['ar' => 'مبيعات', 'en' => 'Sales', 'scopes' => ['branches', 'own']],
        'executor' => ['ar' => 'منفذ', 'en' => 'Executor', 'scopes' => ['assigned', 'own']],
        'finance' => ['ar' => 'مسؤول مالي', 'en' => 'Finance officer', 'scopes' => ['branches']],
        'inventory' => ['ar' => 'مخزون وتوريد', 'en' => 'Inventory and procurement', 'scopes' => ['branches']],
        'content' => ['ar' => 'محتوى', 'en' => 'Content', 'scopes' => ['tenant']],
    ];

    /**
     * @return array{group: string, audience: string, ar: string, en: string, scopes: list<string>, roles: list<string>, role_scopes?: array<string, string>, capability: string|null}
     */
    public static function definition(Permission $permission): array
    {
        return self::DEFINITIONS[$permission->value];
    }

    /**
     * Default scope of a permission inside a role template: the role's preferred scope when the permission
     * allows it, otherwise the permission's narrowest allowed scope (facility-level actions only allow `tenant`).
     */
    public static function defaultScopeFor(Permission $permission, string $role): Scope
    {
        $definition = self::definition($permission);

        if (isset($definition['role_scopes'][$role])) {
            return Scope::from($definition['role_scopes'][$role]);
        }

        foreach (self::ROLES[$role]['scopes'] as $preferred) {
            if (in_array($preferred, $definition['scopes'], true)) {
                return Scope::from($preferred);
            }
        }

        return Scope::from($definition['scopes'][0]);
    }

    /**
     * Permissions a default role template holds. The owner holds every staff permission.
     *
     * @return list<Permission>
     */
    public static function forRole(string $role): array
    {
        return array_values(array_filter(
            Permission::cases(),
            fn (Permission $p) => $p->audience() === Audience::Staff
                && ($role === 'owner' || in_array($role, self::definition($p)['roles'], true)),
        ));
    }
