#!/usr/bin/env node
// Generates src/resources/css/opsone/tokens.css from docs/design-system/source/tokens.json.
// Run from the repository root: node scripts/design-tokens.mjs   (add --check to fail on drift)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'docs/design-system/source/tokens.json'), 'utf8'));
const target = resolve(root, 'src/resources/css/opsone/tokens.css');

const ref = (v) => v.replace(/^\{(.+)\}$/, 'var(--$1)');
const light = [], dark = [], contrast = [], raw = [];

for (const t of tokens.color.tokens) {
    if (typeof t.value === 'string') {
        raw.push(`    --${t.name}: ${t.value};`);
        continue;
    }
    if (t.value.light !== undefined) light.push(`    --${t.name}: ${ref(t.value.light)};`);
    if (t.value.dark !== undefined) dark.push(`    --${t.name}: ${ref(t.value.dark)};`);
    if (t.value.contrast !== undefined) contrast.push(`    --${t.name}: ${ref(t.value.contrast)};`);
}

const shadow = tokens.shadow.tokens[0].value;
const size = tokens.size.tokens.map((s) => `    --${s.name}: ${s.value};`);
const space = tokens.spacing.tokens.map((s) => `    --${s.name}: ${s.value};`);
const radius = tokens.radius.tokens.map((s) => `    --${s.name}: ${s.value};`);
const z = tokens.zIndex.tokens.map((s) => `    --${s.name}: ${s.value};`);

const out = `/* GENERATED by scripts/design-tokens.mjs from docs/design-system/source/tokens.json — do not edit by hand. */

:root {
    color-scheme: light;
${raw.join('\n')}
${light.join('\n')}
    --o1-shadow-raised: ${shadow.light};
${size.join('\n')}
${space.join('\n')}
${radius.join('\n')}
${z.join('\n')}
}

.dark,
[data-theme='dark'] {
    color-scheme: dark;
${dark.join('\n')}
    --o1-shadow-raised: ${shadow.dark};
}

/* High contrast inherits light for every role it does not override (design-system rule). */
[data-theme='contrast'] {
    color-scheme: light;
${contrast.join('\n')}
}
`;

if (process.argv.includes('--check')) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== out) {
        console.error('tokens.css is out of date. Run: node scripts/design-tokens.mjs');
        process.exit(1);
    }
    process.exit(0);
}
writeFileSync(target, out);
console.log('wrote', target);
